/**
 * Generates Asterisk PJSIP configuration from validated trunk settings. Pure and side-effect free:
 * a reconcile job (Phase 2) writes the output and issues `pjsip reload` for changed trunks only, so the PBX is never restarted.
 * Every value is validated against a strict character set before it can reach a config file (no section/newline injection).
 */
export interface PjsipTrunkInput {
  id: string;
  host: string;
  port: number;
  transport: 'udp' | 'tcp' | 'tls';
  authMode: 'registration' | 'ip';
  username?: string | null;
  authId?: string | null;
  password?: string | null;
  realm?: string | null;
  outboundProxy?: string | null;
  registrationExpirySeconds: number;
  codecs: string[];
  srtp?: boolean;
}

const HOST = /^[A-Za-z0-9]([A-Za-z0-9.-]{0,251}[A-Za-z0-9])?$/;
const USER = /^[A-Za-z0-9._@+-]{1,64}$/;
const PROXY = /^[A-Za-z0-9.-]{1,253}(:[0-9]{1,5})?$/;
const CODECS = new Set(['ulaw', 'alaw', 'g722', 'opus', 'g729', 'gsm']);
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

export const trunkEndpointName = (id: string): string => {
  if (!UUID.test(id)) throw new Error('invalid trunk id');
  return `trunk_${id.replace(/-/g, '')}`;
};

function check(ok: boolean, what: string): void {
  if (!ok) throw new Error(`Cannot generate PJSIP config: invalid ${what}`);
}

export function renderPjsipTrunk(t: PjsipTrunkInput, opts: { maskSecrets?: boolean } = {}): string {
  const ep = trunkEndpointName(t.id);
  check(HOST.test(t.host), 'host');
  check(Number.isInteger(t.port) && t.port >= 1 && t.port <= 65535, 'port');
  check(['udp', 'tcp', 'tls'].includes(t.transport), 'transport');
  check(['registration', 'ip'].includes(t.authMode), 'auth mode');
  check(t.codecs.length > 0 && t.codecs.every((c) => CODECS.has(c)), 'codec list');
  if (t.username) check(USER.test(t.username), 'username');
  if (t.authId) check(USER.test(t.authId), 'auth id');
  if (t.realm) check(HOST.test(t.realm), 'realm');
  if (t.outboundProxy) check(PROXY.test(t.outboundProxy), 'outbound proxy');
  check(Number.isInteger(t.registrationExpirySeconds) && t.registrationExpirySeconds >= 60 && t.registrationExpirySeconds <= 3600, 'registration expiry');
  const password = opts.maskSecrets ? '********' : t.password ?? '';
  if (!opts.maskSecrets && t.password) check(/^[^\r\n\0;]{1,200}$/.test(t.password), 'password characters');

  const uri = `sip:${t.host}:${t.port}${t.transport === 'udp' ? '' : `;transport=${t.transport}`}`;
  const lines: string[] = [
    `; Generated by Project Dialer for trunk ${t.id} - do not edit`,
    `[${ep}]`,
    'type=endpoint',
    `transport=transport-${t.transport}`,
    'context=from-trunk',
    'disallow=all',
    `allow=${t.codecs.join(',')}`,
    `aors=${ep}`,
    'direct_media=no',
    ...(t.srtp ? ['media_encryption=sdes'] : []),
    ...(t.outboundProxy ? [`outbound_proxy=sip:${t.outboundProxy}\\;lr`] : []),
    ...(t.authMode === 'registration' ? [`outbound_auth=${ep}_auth`] : []),
    `from_domain=${t.realm || t.host}`,
    '',
    `[${ep}]`,
    'type=aor',
    `contact=${uri}`,
    'qualify_frequency=60',
  ];
  if (t.authMode === 'registration') {
    check(!!t.username, 'username (required for registration trunks)');
    lines.push(
      '',
      `[${ep}_auth]`,
      'type=auth',
      'auth_type=userpass',
      `username=${t.authId || t.username}`,
      `password=${password}`,
      ...(t.realm ? [`realm=${t.realm}`] : []),
      '',
      `[${ep}_reg]`,
      'type=registration',
      `outbound_auth=${ep}_auth`,
      `server_uri=sip:${t.host}:${t.port}`,
      `client_uri=sip:${t.username}@${t.realm || t.host}`,
      `expiration=${t.registrationExpirySeconds}`,
      'retry_interval=60',
    );
  } else {
    lines.push('', `[${ep}_id]`, 'type=identify', `endpoint=${ep}`, `match=${t.host}`);
  }
  return lines.join('\n') + '\n';
}
